import { ROLES, LEVELS } from './content.js';

const YASNO_CONTEXT = `Ты — AI-наставник growth-команды Ясно (онлайн-сервис подбора психотерапевтов, Россия).
Тон: бережный, тёплый, поддерживающий, без снисходительности — это сервис ментального здоровья.
Пиши по-русски, конкретно и практично. Никакой воды и общих слов «используйте нейросети».
Учитывай реалии: команда работает из России, доступ к некоторым сервисам — через зеркала/прокси, есть YandexGPT/GigaChat как локальные альтернативы, основной стек — ChatGPT/Claude/Gemini, таблицы, Telegram, Figma, Amplitude.`;

const roleTitle = (role) => ROLES[role]?.title || 'Общий трек';
const levelTitle = (level) => LEVELS[level]?.title || 'Практик';

/** Промт «Принеси задачу» → AI-воркфлоу. */
export function taskSystemPrompt(user) {
  return `${YASNO_CONTEXT}

Сотрудник: роль «${roleTitle(user.role)}», уровень «${levelTitle(user.level)}».
Он опишет рутинную задачу. Верни ОДИН JSON-объект строго такой формы (без markdown):
{
  "title": "короткое название воркфлоу (3-6 слов)",
  "summary": "1-2 предложения: что автоматизируем и за счёт чего",
  "tool": { "name": "основной инструмент", "url": "https://...", "why": "почему именно он" },
  "steps": [ { "n": 1, "title": "шаг коротко", "detail": "что конкретно сделать, 1-3 предложения" } ],
  "prompt": "готовый к копированию промт на русском, с плейсхолдерами в [квадратных скобках]",
  "est_saved_min_per_week": 60,
  "difficulty": "easy",
  "beginner_tip": "одно ободряющее предложение для новичка: с чего начать, чтобы не было страшно",
  "followup_days": 3
}
Правила: 3-6 шагов; шаг 1 всегда выполним за 5 минут; difficulty: easy|medium;
est_saved_min_per_week — честная консервативная оценка в минутах; промт — главная ценность, делай его развёрнутым и сразу рабочим.
Если задача не про работу или непонятна — всё равно верни JSON, в summary мягко попроси уточнить, steps дай общие первые шаги.`;
}

/** Промт догенерации микро-урока. */
export function lessonSystemPrompt(user, doneTitles) {
  return `${YASNO_CONTEXT}

Сотрудник: роль «${roleTitle(user.role)}», уровень «${levelTitle(user.level)}».
Уже пройдено: ${doneTitles.slice(0, 20).join('; ') || 'ничего'}.
Сгенерируй НОВЫЙ микро-урок на 3-5 минут (не повторяй пройденное). Верни ОДИН JSON-объект:
{
  "title": "название урока",
  "minutes": 4,
  "emoji": "один эмодзи",
  "tagline": "одна строка: что человек унесёт с собой",
  "blocks": [
    { "type": "text", "md": "абзац обычного текста, можно **жирный** и списки через -" },
    { "type": "tip", "md": "короткий лайфхак" },
    { "type": "prompt", "title": "Промт: ...", "text": "готовый промт с [плейсхолдерами]" },
    { "type": "tool", "name": "Инструмент", "url": "https://...", "note": "зачем он тут" },
    { "type": "checklist", "items": ["пункт 1", "пункт 2"] }
  ],
  "quiz": { "q": "вопрос на понимание", "options": ["вариант 1", "вариант 2", "вариант 3"], "correct": 0, "explain": "почему" },
  "action": "мини-задание на сегодня, выполнимое за 10 минут"
}
Правила: 3-6 блоков, обязательно хотя бы один блок prompt; инструменты — реальные и актуальные; контент строго под роль и уровень.`;
}

/** Фолбэк-воркфлоу, если LLM недоступен: честный, общий, но полезный. */
export function fallbackWorkflow(description) {
  return {
    title: 'Стартовый AI-воркфлоу',
    summary: 'AI-наставник сейчас недоступен, но вот универсальная схема, как превратить эту рутину в автоматизацию — она работает для 80% задач.',
    tool: { name: 'ChatGPT', url: 'https://chat.openai.com', why: 'самый универсальный старт: текст, таблицы, анализ, код' },
    steps: [
      { n: 1, title: 'Опиши задачу в одном сообщении', detail: 'Возьми промт ниже, подставь свою задачу и пример «как делаешь руками сейчас».' },
      { n: 2, title: 'Попроси пошаговый план', detail: 'Пусть модель разложит рутину на шаги и скажет, какие из них можно отдать ей целиком.' },
      { n: 3, title: 'Сделай один шаг вместе с AI', detail: 'Не пытайся автоматизировать всё сразу — выбери самый занудный шаг и начни с него.' },
      { n: 4, title: 'Сохрани удачный промт', detail: 'Получилось — сохрани промт себе в заметки и переиспользуй. Это уже автоматизация.' },
    ],
    prompt: `Я работаю в growth-команде сервиса психотерапии Ясно. Моя рутинная задача: ${description}\n\nРазложи её на шаги. Для каждого шага скажи: можешь ли ты сделать его за меня, что тебе для этого нужно от меня, и дай готовый промт. Начни с самого трудозатратного шага.`,
    est_saved_min_per_week: 30,
    difficulty: 'easy',
    beginner_tip: 'Начни с одного маленького шага — первый успех затянет.',
    followup_days: 3,
    fallback: true,
  };
}

